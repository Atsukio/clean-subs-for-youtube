// Generates the Material Design 3 theme and bundles the Roboto font files.
//   npm run assets
// Outputs (committed, so the extension itself needs no build step):
//   ui/theme.css               colour roles for the popup (follows the OS light/dark setting)
//   content/theme.css          the same roles for the tab bar on YouTube (follows html[dark])
//   fonts/*.woff2              Roboto 400 and 500, latin subset, plus its licence
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  Hct,
  SchemeTonalSpot,
  MaterialDynamicColors,
  DynamicColor,
  argbFromHex,
  hexFromArgb,
} from "@material/material-color-utilities";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const SEED = "#3d6fd8"; // blue taken from the icon

const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());

function roles(isDark) {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(SEED)), isDark, 0.0);
  const out = [];
  for (const [name, color] of Object.entries(MaterialDynamicColors)) {
    if (!(color instanceof DynamicColor)) continue;
    out.push(`  --md-sys-color-${kebab(name)}: ${hexFromArgb(color.getArgb(scheme))};`);
  }
  return out.join("\n");
}

const header = `/* Generated by tools/build-assets.mjs from seed ${SEED}. Do not edit by hand. */\n`;

// Shape, type and state tokens from the Material Design 3 spec
const shared = `
  --md-sys-shape-extra-small: 4px;
  --md-sys-shape-small: 8px;
  --md-sys-shape-medium: 12px;
  --md-sys-shape-large: 16px;
  --md-sys-shape-extra-large: 28px;
  --md-sys-shape-full: 9999px;

  --md-sys-state-hover: 8%;
  --md-sys-state-focus: 10%;
  --md-sys-state-pressed: 10%;
  --md-sys-state-disabled-content: 38%;
  --md-sys-state-disabled-container: 12%;

  --md-ref-typeface: "Roboto", system-ui, sans-serif;
  --md-sys-typescale-title-large: 400 22px/28px var(--md-ref-typeface);
  --md-sys-typescale-title-medium: 500 16px/24px var(--md-ref-typeface);
  --md-sys-typescale-title-small: 500 14px/20px var(--md-ref-typeface);
  --md-sys-typescale-label-large: 500 14px/20px var(--md-ref-typeface);
  --md-sys-typescale-label-medium: 500 12px/16px var(--md-ref-typeface);
  --md-sys-typescale-body-large: 400 16px/24px var(--md-ref-typeface);
  --md-sys-typescale-body-medium: 400 14px/20px var(--md-ref-typeface);
  --md-sys-typescale-body-small: 400 12px/16px var(--md-ref-typeface);
`;

const popupCss =
  header +
  `@font-face { font-family: "Roboto"; font-weight: 400; font-style: normal; font-display: block;
  src: url("../fonts/roboto-latin-400-normal.woff2") format("woff2"); }
@font-face { font-family: "Roboto"; font-weight: 500; font-style: normal; font-display: block;
  src: url("../fonts/roboto-latin-500-normal.woff2") format("woff2"); }

:root {
${roles(false)}
${shared}}

@media (prefers-color-scheme: dark) {
  :root {
${roles(true).replace(/^/gm, "  ")}
  }
}
`;

const contentCss =
  header +
  `/* Scoped to the injected tab bar so nothing leaks into YouTube's own styles. YouTube's
   Roboto is already loaded on the page, so no font files are needed here. */
#rysl-tabs {
${roles(false)}
${shared}}

html[dark] #rysl-tabs {
${roles(true)}
}
`;

fs.writeFileSync(path.join(root, "ui", "theme.css"), popupCss);
fs.writeFileSync(path.join(root, "content", "theme.css"), contentCss);

const fontSrc = path.join(root, "node_modules", "@fontsource", "roboto");
const fontDst = path.join(root, "fonts");
fs.mkdirSync(fontDst, { recursive: true });
for (const weight of [400, 500]) {
  const file = `roboto-latin-${weight}-normal.woff2`;
  fs.copyFileSync(path.join(fontSrc, "files", file), path.join(fontDst, file));
}
fs.copyFileSync(path.join(fontSrc, "LICENSE"), path.join(fontDst, "LICENSE.txt"));

console.log("Wrote ui/theme.css, content/theme.css and fonts/");
